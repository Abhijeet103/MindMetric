    items.filter(pk__in=retired_ids).update(is_active=False)
    for first, second, difficulty, relationship, odd_words in WORD_CONCEPTS:
        for odd in odd_words:
            items.get_or_create(pair_word_1=first, pair_word_2=second, odd_word=odd, difficulty=difficulty, defaults={"relationship_type": "synonyms", "explanation": f"{relationship}; {odd} does not share that meaning.", "tags": ["original", "semantic-pair", "2026-11"]})

